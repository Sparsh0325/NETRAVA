CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chain_index BIGINT NOT NULL UNIQUE,
  timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
  actor_username VARCHAR(100) NOT NULL,
  actor_role VARCHAR(50) NOT NULL,
  actor_badge_number VARCHAR(50),
  agency VARCHAR(100),
  action VARCHAR(100) NOT NULL,
  resource VARCHAR(255) NOT NULL,
  details TEXT,
  previous_hash VARCHAR(64) NOT NULL,
  hash VARCHAR(64) NOT NULL,
  hash_version INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS audit_chain_state (
  id INTEGER PRIMARY KEY,
  last_index BIGINT NOT NULL,
  last_hash VARCHAR(64) NOT NULL
);
INSERT INTO audit_chain_state(id, last_index, last_hash)
SELECT 1, 0, REPEAT('0', 64) WHERE NOT EXISTS (SELECT 1 FROM audit_chain_state WHERE id=1);
CREATE TABLE IF NOT EXISTS ingestion_jobs (
  id UUID PRIMARY KEY, original_file_name VARCHAR(255) NOT NULL, media_type VARCHAR(100) NOT NULL,
  status VARCHAR(20) NOT NULL, rows_processed INTEGER NOT NULL DEFAULT 0, agency VARCHAR(100) NOT NULL,
  created_by_id BIGINT, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
